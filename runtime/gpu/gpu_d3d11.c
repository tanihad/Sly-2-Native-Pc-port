/* Render thread: sole owner of the Direct3D 11 device, immediate context and swap chain
 * (notes/d3d11-renderer.md 2.1). Device creation (hardware adapter or WARP, feature level 11_1, with
 * or without a window), capability check, shader objects from the build-time blobs, and the loop
 * that executes the command chunks queued by the GS side (gpu_cmd.c).
 *
 * Environment: PS2_GPU_DEBUG=1 asks for the D3D11 debug layer (falls back silently when the
 * Graphics Tools optional feature is not installed). */
#include "gpu_internal.h"

#include <stdarg.h>
#include <stdatomic.h>
#include <stdlib.h>

#include "gpu_shaders.h"                 /* generated by scripts/hlslc.c (build/gen) */

