/* ---- table construction ------------------------------------------------------------------------ */

static int parse_code(const char* s, uint32_t* bits) {
    int len = 0;
    uint32_t v = 0;
    for (; *s; s++) {
        if (*s == ' ') continue;
        if (len == 24) return -1;
        v = (v << 1) | (uint32_t)(*s == '1');
        len++;
    }
    *bits = v;
    return len;
}

static int fill(ipu_vlc_entry* e, int count, ipu_vlc_entry v) {
    for (int i = 0; i < count; i++) {
        if (e[i].len || e[i].sub) return -1;            /* overlaps another code */
        e[i] = v;
    }
    return 0;
}

int ipu_vlc_build(ipu_vlc_table* t, const ipu_vlc_code* codes, int n) {
    memset(t, 0, sizeof *t);
    /* first pass: codes up to 8 bits, and the width each 8-bit prefix of a longer code needs */
    uint8_t width[256] = { 0 };
    for (int i = 0; i < n; i++) {
        uint32_t c;
        int len = parse_code(codes[i].code, &c);
        if (len < 1 || len > 16) return -1;
        if (len > t->max_len) t->max_len = len;
        if (len <= 8) {
            ipu_vlc_entry v = { codes[i].val, (uint8_t)len, 0 };
            if (fill(&t->l1[c << (8 - len)], 1 << (8 - len), v)) return -1;
        } else {
            uint32_t prefix = c >> (len - 8);
            if (len - 8 > width[prefix]) width[prefix] = (uint8_t)(len - 8);
        }
    }
    for (int p = 0; p < 256; p++) {
        if (!width[p]) continue;
        if (t->l1[p].len || t->l2_used + (1 << width[p]) > (int)(sizeof t->l2 / sizeof t->l2[0])) return -1;
        t->l1[p] = (ipu_vlc_entry){ (int16_t)t->l2_used, 0, width[p] };
        t->l2_used += 1 << width[p];
    }
    /* second pass: the longer codes */
    for (int i = 0; i < n; i++) {
        uint32_t c;
        int len = parse_code(codes[i].code, &c);
        if (len <= 8) continue;
        ipu_vlc_entry sub = t->l1[c >> (len - 8)];
        int extra = len - 8;
        uint32_t rest = c & ((1u << extra) - 1);
        ipu_vlc_entry v = { codes[i].val, (uint8_t)len, 0 };
        if (fill(&t->l2[sub.val + (rest << (sub.sub - extra))], 1 << (sub.sub - extra), v)) return -1;
    }
    return 0;
}

void ipu_vlc_init(void) {
    static int done;
    if (done) return;
    for (int i = 0; i < IPU_VLC_COUNT; i++)
        if (ipu_vlc_build(&ipu_vlc_tables[i], ipu_vlc_codes[i], ipu_vlc_code_count[i])) abort();
    done = 1;
}

/* ---- DCT coefficients ------------------------------------------------------------------------- */

int ipu_dct_symbol(uint32_t bits, int table, int first, int mpeg1, int* run, int* level) {
    if (first && table == 0 && (bits >> 31)) {          /* "1s": (0, +-1) */
        *run = 0;
        *level = (bits & 0x40000000u) ? -1 : 1;
        return 2;
    }
    ipu_vlc_entry e = ipu_vlc_get(&ipu_vlc_tables[IPU_VLC_DCT0 + table], bits);
    if (!e.len) return 0;
    if (e.val == IPU_DCT_EOB) { *run = -1; *level = 0; return e.len; }
    if (e.val == IPU_DCT_ESCAPE) {                      /* 6-bit escape, 6-bit run, level */
        uint32_t b = bits << 6;
        *run = (int)(b >> 26);
        b <<= 6;
        if (!mpeg1) {                                   /* 12-bit two's complement */
            *level = (int32_t)b >> 20;
            return 24;
        }
        int l = (int32_t)b >> 24;                       /* MPEG-1: 8 bits, or 16 for |level| >= 128 */
        if (l == 0) { *level = (int)((b >> 16) & 0xFF); return 28; }
        if (l == -128) { *level = (int)((b >> 16) & 0xFF) - 256; return 28; }
        *level = l;
        return 20;
    }
    *run = e.val & 0xFF;
    *level = e.val >> 8;
    if (bits & (0x80000000u >> e.len)) *level = -*level;
    return e.len + 1;
}
