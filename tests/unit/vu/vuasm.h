/* Tiny VU micro-code assembler for the unit tests: each macro returns one 32-bit instruction word.
 * Encodings from Sony's VU User's Manual. Dest masks use the instruction's bit order (x = 8). */
#pragma once
#include <stdint.h>

enum { DX = 8, DY = 4, DZ = 2, DW = 1, DXY = 12, DXZ = 10, DXW = 9, DXYZ = 14, DXYZW = 15 };
enum { FX = 0, FY = 1, FZ = 2, FW = 3 };

/* upper flags */
#define UI (1u << 31)
#define UE (1u << 30)

/* ---- upper ---- */
#define UP1(d, ft, fs, fd, f6) ((uint32_t)(d) << 21 | (uint32_t)(ft) << 16 | (uint32_t)(fs) << 11 | (uint32_t)(fd) << 6 | (f6))
#define UP2(d, ft, fs, k) ((uint32_t)(d) << 21 | (uint32_t)(ft) << 16 | (uint32_t)(fs) << 11 | (uint32_t)((k) >> 2) << 6 | 0x3C | ((k) & 3))

#define U_NOP              0x000002FFu
#define U_ADD(d, fd, fs, ft)   UP1(d, ft, fs, fd, 0x28)
#define U_SUB(d, fd, fs, ft)   UP1(d, ft, fs, fd, 0x2C)
#define U_MUL(d, fd, fs, ft)   UP1(d, ft, fs, fd, 0x2A)
#define U_MADD(d, fd, fs, ft)  UP1(d, ft, fs, fd, 0x29)
#define U_MSUB(d, fd, fs, ft)  UP1(d, ft, fs, fd, 0x2D)
#define U_MAX(d, fd, fs, ft)   UP1(d, ft, fs, fd, 0x2B)
#define U_MINI(d, fd, fs, ft)  UP1(d, ft, fs, fd, 0x2F)
#define U_OPMSUB(d, fd, fs, ft) UP1(d, ft, fs, fd, 0x2E)
#define U_ADDbc(d, fd, fs, ft, bc)  UP1(d, ft, fs, fd, 0x00 + (bc))
#define U_SUBbc(d, fd, fs, ft, bc)  UP1(d, ft, fs, fd, 0x04 + (bc))
#define U_MADDbc(d, fd, fs, ft, bc) UP1(d, ft, fs, fd, 0x08 + (bc))
#define U_MAXbc(d, fd, fs, ft, bc)  UP1(d, ft, fs, fd, 0x10 + (bc))
#define U_MINIbc(d, fd, fs, ft, bc) UP1(d, ft, fs, fd, 0x14 + (bc))
#define U_MULbc(d, fd, fs, ft, bc)  UP1(d, ft, fs, fd, 0x18 + (bc))
#define U_MULq(d, fd, fs)      UP1(d, 0, fs, fd, 0x1C)
#define U_MAXi(d, fd, fs)      UP1(d, 0, fs, fd, 0x1D)
#define U_MULi(d, fd, fs)      UP1(d, 0, fs, fd, 0x1E)
#define U_ADDq(d, fd, fs)      UP1(d, 0, fs, fd, 0x20)
#define U_ADDi(d, fd, fs)      UP1(d, 0, fs, fd, 0x22)
#define U_SUBi(d, fd, fs)      UP1(d, 0, fs, fd, 0x26)
#define U_ADDA(d, fs, ft)      UP2(d, ft, fs, 0x28)
#define U_MULA(d, fs, ft)      UP2(d, ft, fs, 0x2A)
#define U_MULAbc(d, fs, ft, bc)  UP2(d, ft, fs, 0x18 + (bc))
#define U_MADDAbc(d, fs, ft, bc) UP2(d, ft, fs, 0x08 + (bc))
#define U_OPMULA(d, fs, ft)    UP2(d, ft, fs, 0x2E)
#define U_ITOF(d, ft, fs, k)   UP2(d, ft, fs, 0x10 + (k))   /* k: 0 = ITOF0, 1 = 4, 2 = 12, 3 = 15 */
#define U_FTOI(d, ft, fs, k)   UP2(d, ft, fs, 0x14 + (k))
#define U_ABS(d, ft, fs)       UP2(d, ft, fs, 0x1D)
#define U_CLIP(fs, ft)         UP2(DXYZ, ft, fs, 0x1F)

/* ---- lower ---- */
#define L_NOP 0x8000033Cu
#define LO7(op) ((uint32_t)(op) << 25)
#define IMM11(v) ((uint32_t)(v) & 0x7FF)
#define L_LQ(d, ft, is, imm)  (LO7(0x00) | (uint32_t)(d) << 21 | (uint32_t)(ft) << 16 | (uint32_t)(is) << 11 | IMM11(imm))
#define L_SQ(d, fs, it, imm)  (LO7(0x01) | (uint32_t)(d) << 21 | (uint32_t)(it) << 16 | (uint32_t)(fs) << 11 | IMM11(imm))
#define L_ILW(d, it, is, imm) (LO7(0x04) | (uint32_t)(d) << 21 | (uint32_t)(it) << 16 | (uint32_t)(is) << 11 | IMM11(imm))
#define L_ISW(d, it, is, imm) (LO7(0x05) | (uint32_t)(d) << 21 | (uint32_t)(it) << 16 | (uint32_t)(is) << 11 | IMM11(imm))
#define L_IADDIU(it, is, imm) (LO7(0x08) | ((uint32_t)(imm) >> 11 & 15) << 21 | (uint32_t)(it) << 16 | (uint32_t)(is) << 11 | ((uint32_t)(imm) & 0x7FF))
#define L_ISUBIU(it, is, imm) (LO7(0x09) | ((uint32_t)(imm) >> 11 & 15) << 21 | (uint32_t)(it) << 16 | (uint32_t)(is) << 11 | ((uint32_t)(imm) & 0x7FF))
#define L_FCEQ(imm)   (LO7(0x10) | ((uint32_t)(imm) & 0xFFFFFF))
#define L_FCSET(imm)  (LO7(0x11) | ((uint32_t)(imm) & 0xFFFFFF))
#define L_FCAND(imm)  (LO7(0x12) | ((uint32_t)(imm) & 0xFFFFFF))
#define L_FCOR(imm)   (LO7(0x13) | ((uint32_t)(imm) & 0xFFFFFF))
#define FS12(imm) (((uint32_t)(imm) >> 11 & 1) << 21 | ((uint32_t)(imm) & 0x7FF))
#define L_FSEQ(it, imm)  (LO7(0x14) | (uint32_t)(it) << 16 | FS12(imm))
#define L_FSSET(imm)     (LO7(0x15) | FS12(imm))
#define L_FSAND(it, imm) (LO7(0x16) | (uint32_t)(it) << 16 | FS12(imm))
#define L_FSOR(it, imm)  (LO7(0x17) | (uint32_t)(it) << 16 | FS12(imm))
#define L_FMEQ(it, is)   (LO7(0x18) | (uint32_t)(it) << 16 | (uint32_t)(is) << 11)
#define L_FMAND(it, is)  (LO7(0x1A) | (uint32_t)(it) << 16 | (uint32_t)(is) << 11)
#define L_FMOR(it, is)   (LO7(0x1B) | (uint32_t)(it) << 16 | (uint32_t)(is) << 11)
#define L_FCGET(it)      (LO7(0x1C) | (uint32_t)(it) << 16)
#define L_B(off)         (LO7(0x20) | IMM11(off))          /* off: in instructions, relative to the next */
#define L_BAL(it, off)   (LO7(0x21) | (uint32_t)(it) << 16 | IMM11(off))
#define L_JR(is)         (LO7(0x24) | (uint32_t)(is) << 11)
#define L_JALR(it, is)   (LO7(0x25) | (uint32_t)(it) << 16 | (uint32_t)(is) << 11)
#define L_IBEQ(it, is, off) (LO7(0x28) | (uint32_t)(it) << 16 | (uint32_t)(is) << 11 | IMM11(off))
#define L_IBNE(it, is, off) (LO7(0x29) | (uint32_t)(it) << 16 | (uint32_t)(is) << 11 | IMM11(off))
#define L_IBLTZ(is, off) (LO7(0x2C) | (uint32_t)(is) << 11 | IMM11(off))
#define L_IBGTZ(is, off) (LO7(0x2D) | (uint32_t)(is) << 11 | IMM11(off))
#define L_IBLEZ(is, off) (LO7(0x2E) | (uint32_t)(is) << 11 | IMM11(off))
#define L_IBGEZ(is, off) (LO7(0x2F) | (uint32_t)(is) << 11 | IMM11(off))
#define LS1(it, is, id, f) (0x80000000u | (uint32_t)(it) << 16 | (uint32_t)(is) << 11 | (uint32_t)(id) << 6 | (f))
#define L_IADD(id, is, it) LS1(it, is, id, 0x30)
#define L_ISUB(id, is, it) LS1(it, is, id, 0x31)
#define L_IAND(id, is, it) LS1(it, is, id, 0x34)
#define L_IOR(id, is, it)  LS1(it, is, id, 0x35)
#define L_IADDI(it, is, imm5) LS1(it, is, ((uint32_t)(imm5) & 31), 0x32)
#define LS2(d, t, s, k) (0x80000000u | (uint32_t)(d) << 21 | (uint32_t)(t) << 16 | (uint32_t)(s) << 11 | (uint32_t)((k) >> 2) << 6 | 0x3C | ((k) & 3))
#define L_MOVE(d, ft, fs)  LS2(d, ft, fs, 0x30)
#define L_MR32(d, ft, fs)  LS2(d, ft, fs, 0x31)
#define L_LQI(d, ft, is)   LS2(d, ft, is, 0x34)
#define L_SQI(d, fs, it)   LS2(d, it, fs, 0x35)
#define L_LQD(d, ft, is)   LS2(d, ft, is, 0x36)
#define L_SQD(d, fs, it)   LS2(d, it, fs, 0x37)
#define L_DIV(fs, fsf, ft, ftf)   LS2(((ftf) << 2 | (fsf)), ft, fs, 0x38)
#define L_SQRT(ft, ftf)           LS2(((ftf) << 2), ft, 0, 0x39)
#define L_RSQRT(fs, fsf, ft, ftf) LS2(((ftf) << 2 | (fsf)), ft, fs, 0x3A)
#define L_WAITQ            LS2(0, 0, 0, 0x3B)
#define L_MTIR(it, fs, fsf) LS2((fsf), it, fs, 0x3C)
#define L_MFIR(d, ft, is)  LS2(d, ft, is, 0x3D)
#define L_ILWR(d, it, is)  LS2(d, it, is, 0x3E)
#define L_ISWR(d, it, is)  LS2(d, it, is, 0x3F)
#define L_RNEXT(d, ft)     LS2(d, ft, 0, 0x40)
#define L_RGET(d, ft)      LS2(d, ft, 0, 0x41)
#define L_RINIT(fs, fsf)   LS2((fsf), 0, fs, 0x42)
#define L_RXOR(fs, fsf)    LS2((fsf), 0, fs, 0x43)
#define L_MFP(d, ft)       LS2(d, ft, 0, 0x64)
#define L_XTOP(it)         LS2(0, it, 0, 0x68)
#define L_XITOP(it)        LS2(0, it, 0, 0x69)
#define L_XGKICK(is)       LS2(0, 0, is, 0x6C)
#define L_ESADD(fs)        LS2(0, 0, fs, 0x70)
#define L_ELENG(fs)        LS2(0, 0, fs, 0x72)
#define L_ERLENG(fs)       LS2(0, 0, fs, 0x73)
#define L_ESUM(fs)         LS2(0, 0, fs, 0x76)
#define L_ESQRT(fs, fsf)   LS2((fsf), 0, fs, 0x78)
#define L_ERSQRT(fs, fsf)  LS2((fsf), 0, fs, 0x79)
#define L_ERCPR(fs, fsf)   LS2((fsf), 0, fs, 0x7A)
#define L_WAITP            LS2(0, 0, 0, 0x7B)
#define L_ESIN(fs, fsf)    LS2((fsf), 0, fs, 0x7C)
#define L_EATAN(fs, fsf)   LS2((fsf), 0, fs, 0x7D)
#define L_EEXP(fs, fsf)    LS2((fsf), 0, fs, 0x7E)
