/* Sly2-Setup.exe: the "builder installer" (notes/install.md, "Installer").
 *
 * It installs our recompiler, runtime and the pinned build toolchain, checks the player's own disc
 * image, builds sly2.exe on the player's PC (scripts/build_game.py), and installs it with shortcuts and
 * an uninstaller. The setup program carries no game code or data: only our sources (and, in the offline
 * variant, the toolchain archives).
 *
 * Files: main.c (command line, wizard window), engine.c (install / finish / uninstall steps), util.c (log,
 * files, processes, SHA-256, registry, shortcuts, payload), net.c (downloads), disc.c (disc image check).
 */
