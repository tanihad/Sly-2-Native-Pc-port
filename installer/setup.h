/* a pinned toolchain archive (values from scripts/setup-tools.ps1, written by scripts/make_installer.py) */
typedef struct {
    const wchar_t* name;             /* "llvm-mingw 20261006" */
    const wchar_t* dir;              /* folder in builder\tools */
    const wchar_t* file;             /* archive file name */
    const char* file8;
    const wchar_t* url;              /* official download URL */
    const char* sha256;              /* the publisher's SHA-256 (lower case hex) */
    uint64_t size;                   /* archive size in bytes */
    int flatten;                     /* the archive has one top-level folder: that is dir */
    const wchar_t* check;            /* a file that must exist after unpacking */
    int entries;                     /* entries tar unpacks (progress) */
    const wchar_t* excludes;         /* tar options: parts we never use (other CPU targets, debugger) */
    int installed_mb;                /* unpacked size */
    int pm_from, pm_to;              /* its share of the toolchain part of the progress bar (permille) */
} setup_pin;

#include "setup_config.h"            /* generated by scripts/make_installer.py: version, pins, sizes */

#define MAXP 1024                    /* path buffers (wchar_t) */

/* ---- exit codes (also /silent) ---------------------------------------------------------------- */
enum {
    EXIT_OK = 0, EXIT_FAILED = 1, EXIT_USAGE = 2, EXIT_CANCELLED = 3, EXIT_BAD_DISC = 4, EXIT_NO_SPACE = 5,
    EXIT_NEEDS_ADMIN = 6
};

/* ---- one setup run ------------------------------------------------------------------------------ */
typedef void (*progress_fn)(void* ui, int permille, const wchar_t* status, const wchar_t* detail);
typedef void (*logline_fn)(void* ui, const wchar_t* line);

typedef struct setup {
    /* choices */
    wchar_t dir[MAXP];               /* install folder */
    wchar_t iso[MAXP];               /* the player's disc image */
    wchar_t from[MAXP];              /* /from=: local folder with the toolchain (setup.ps1 -From layout) */
    wchar_t mirror[MAXP];            /* /mirror=: download base (URL or folder) instead of the official URLs */
    wchar_t startmenu[MAXP];         /* /startmenu=: folder for the Start menu shortcut (tests) */
    wchar_t desktop[MAXP];           /* /desktopdir=: folder for the desktop shortcut (tests) */
    wchar_t userdata[MAXP];          /* /userdata=: the game's user data folder (default %LOCALAPPDATA%\Sly2) */
    wchar_t regkey[MAXP];            /* /regkey=: uninstall registry key (default ...\Uninstall\Sly2-PC) */
    int allusers;                    /* Program Files install: HKLM, all-users Start menu (elevated) */
    int offline_only;                /* /offline: never download */
    int desktop_shortcut;            /* finish: create a desktop shortcut */
    int keep_build;                  /* finish: keep the build intermediates */
    int keep_tools;                  /* finish: keep the toolchain (faster updates) */
    int play;                        /* finish: start the game */
    int silent;                      /* no window, no questions */
    int uitest;                      /* /uitest: message boxes go to the log */
    int delete_saves;                /* uninstall: also remove the user data folder (-1 = ask) */
    int existing;                    /* an installation was found in dir */
    int log_fixed;                   /* /log=: keep logging there (not <dir>\setup.log) */
    int quiet_child;                 /* run_hidden: do not copy the program's output into the log (tar -v) */

    /* run state */
    volatile LONG cancel;
    HANDLE job;                      /* the running child process tree (TerminateJobObject on cancel) */
    CRITICAL_SECTION lock;
    void* ui;
    progress_fn progress;
    logline_fn logline;
    int pm_base, pm_span;            /* current step's share of the progress bar (permille) */
    wchar_t status[512];
    wchar_t error[2048];             /* why the last step failed (shown to the player) */
    uint64_t used_build, used_tools; /* measured after the build (bytes) */
} setup_t;

